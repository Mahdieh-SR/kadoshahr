-- عنوان کادرهای انتخاب در صفحه‌ی محصول
--
-- هر محصول سه محور دارد (platform / region / capacity) ولی عنوانی که مشتری
-- می‌بیند از محصولی به محصول دیگر فرق می‌کند:
--   گیفت‌کارت اپل   → «گیفت کارت»
--   پلی‌استیشن پلاس → «پلن اکانت» + «مدت زمان اشتراک» + «ظرفیت اکانت»
--   اپل تی‌وی پلاس  → فقط «مدت زمان اشتراک»
--
-- شکل داده:  {"capacity": "مدت زمان اشتراک", "region": "ریجن اکانت"}
-- محوری که کلیدش نباشد، کادرش در صفحه نمایش داده نمی‌شود.
-- NULL یعنی عنوان‌های پیش‌فرض (پلتفرم / ریجن / حجم).


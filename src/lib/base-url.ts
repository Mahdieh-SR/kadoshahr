/**
 * آدرس عمومی سایت — همیشه بدون اسلش آخر.
 *
 * ⚠️ چرا `APP_BASE_URL` و نه `NEXT_PUBLIC_BASE_URL`؟
 *
 * Next هر متغیری با پیشوند `NEXT_PUBLIC_` را **موقع بیلد** داخل کد جاسازی
 * می‌کند. روی سرویس‌هایی مثل رانفلر که بیلد در یک Docker build جدا و بدون
 * متغیرهای محیطی سرویس اجرا می‌شود، نتیجه‌اش این است که مقدار جاسازی‌شده
 * همان پیش‌فرض `localhost` می‌ماند و هرچه در پنل تنظیم کنی بی‌اثر است —
 * بازگشت از درگاه پرداخت و لینک‌های sitemap به آدرس اشتباه می‌روند.
 *
 * چون همه‌ی مصرف‌کننده‌ها سمت سرورند، اسم بدون پیشوند یعنی مقدار **زمان
 * اجرا** خوانده می‌شود. تغییر دامنه دیگر فقط یک متغیر و یک ری‌استارت است،
 * نه یک بیلد کامل.
 *
 * `NEXT_PUBLIC_BASE_URL` هم پذیرفته می‌شود تا تنظیمات قدیمی نشکنند.
 */
export function baseUrl(): string {
  const raw =
    process.env.APP_BASE_URL ??
    process.env.NEXT_PUBLIC_BASE_URL ??
    "http://localhost:3000";

  // اسلش آخر باعث می‌شود آدرس‌ها به شکل `https://site.com//product/x` ساخته
  // شوند؛ یک بار همین باعث خطای بازگشت از درگاه شد.
  return raw.trim().replace(/\/+$/, "");
}

/**
 * «حالت نمایش» — فقط برای ارائه‌ی سایت به کارفرما پیش از راه‌اندازی واقعی.
 *
 * مشکلی که حل می‌کند: در حالت عادیِ production، کد تایید نه روی صفحه نشان
 * داده می‌شود (به دلایل امنیتی) و نه پیامک می‌شود (چون پنل پیامک هنوز وصل
 * نیست). یعنی هیچ‌کس نمی‌تواند وارد شود و پنل‌ها را ببیند.
 *
 * وقتی DEMO_MODE=true باشد، کد دوباره روی صفحه نمایش داده می‌شود و یک نوار
 * هشدار پررنگ بالای همه‌ی صفحات ظاهر می‌شود.
 *
 * ⚠️ پیش از افتتاح واقعی فروشگاه، این کلید باید حذف یا false شود.
 * تا وقتی روشن است، هر کسی می‌تواند با هر شماره‌ای وارد شود.
 */
export function isDemoMode(): boolean {
  return process.env.DEMO_MODE === "true";
}

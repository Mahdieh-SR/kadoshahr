/**
 * کمک‌کننده‌های نمایش متن فارسی در تصاویر OG.
 *
 * موتور تصویرساز (Satori) چینش راست‌به‌چپ را کامل پشتیبانی نمی‌کند:
 *   • ترتیب کلمه‌ها را برعکس می‌چیند
 *   • فاصله‌ی بین کلمه‌ها را کشیده و نامنظم رسم می‌کند
 *
 * راه‌حل: ترتیب را از قبل معکوس می‌کنیم و به‌جای تکیه بر کاراکتر فاصله،
 * هر کلمه را یک عنصر جدا با فاصله‌ی مشخص می‌گذاریم.
 *
 * ⚠️ فقط برای تصاویر OG. مرورگرها خودشان راست‌به‌چپ را درست نمایش می‌دهند.
 */

/** نیم‌فاصله هم مثل فاصله برعکس می‌شود، پس داخل کلمه هم باید معکوس شود */
function fixWord(word: string): string {
  return word.split("‌").reverse().join("‌");
}

/**
 * متن را به کلمه‌های آماده‌ی نمایش تبدیل می‌کند — به ترتیبی که Satori
 * بعد از معکوس کردن، درست نشانشان بدهد.
 */
export function rtlWords(text: string): string[] {
  return text.trim().split(/\s+/).map(fixWord).reverse();
}

/** برای متن‌های تک‌کلمه‌ای یا کوتاه که نیازی به چیدمان جداگانه ندارند */
export function rtlText(text: string): string {
  return rtlWords(text).join(" ");
}
